/**
 * Turns the preset button icons in assets/presets/*.png (256x256, from the "Companion Icons - ZoomOSC and ZoomISO"
 * Canva set) into src/images-presets.ts. The pixels are embedded unchanged at full size (Companion scales them per
 * surface); only metadata chunks (Canva export details) are left out.
 *
 * Some icons are templates with an empty area for text (a group name, an output name, ...). For those the text colour
 * (black or white) is picked from the brightness of that area, so a preset can put its text there.
 *
 * Run with: node scripts/build-preset-icons.mjs
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { PNG } from 'pngjs'
import * as prettier from 'prettier'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const assets = path.join(root, 'assets/presets')

/** The area (as fractions of the icon height) a template icon leaves empty for text */
const TEXT_AREAS = [
	{ match: /^group\d+(Add|Clear|Load|Remove|Replace|Save)$/, from: 0, to: 0.25 }, // the empty top bar
	{ match: /^group(\d+|Host|Spot)Select$/, from: 0.3, to: 0.65 }, // between "SELECT" and the people
	{ match: /^group\d+$/, from: 0.3, to: 1 }, // the body under "GROUP"
	{ match: /^joinMeeting$/, from: 0.3, to: 1 }, // the body under "JOIN"
	{ match: /^(output\d+|audioTemplate)$/, from: 0, to: 0.5 }, // above "OUTPUT n" / "AUDIO n"
]

/** Metadata chunks dropped from the embedded PNGs; they don't affect the image */
const METADATA_CHUNKS = new Set(['iTXt', 'tEXt', 'zTXt', 'eXIf', 'tIME'])

function withoutMetadata(buffer) {
	const chunks = [buffer.subarray(0, 8)]
	for (let offset = 8; offset < buffer.length;) {
		const end = offset + 12 + buffer.readUInt32BE(offset)
		if (!METADATA_CHUNKS.has(buffer.toString('latin1', offset + 4, offset + 8)))
			chunks.push(buffer.subarray(offset, end))
		offset = end
	}
	return Buffer.concat(chunks)
}

function textColor(png, area) {
	let sum = 0
	let count = 0
	for (let y = Math.floor(png.height * area.from); y < Math.floor(png.height * area.to); y++) {
		for (let x = 0; x < png.width; x++) {
			const i = (y * png.width + x) * 4
			sum += 0.2126 * png.data[i] + 0.7152 * png.data[i + 1] + 0.0722 * png.data[i + 2]
			count++
		}
	}
	return sum / count > 140 ? '0x000000' : '0xffffff'
}

const images = {}
const textColors = {}
for (const file of fs
	.readdirSync(assets)
	.filter((f) => f.endsWith('.png'))
	.sort()) {
	const key = path.basename(file, '.png')
	const buffer = withoutMetadata(fs.readFileSync(path.join(assets, file)))
	images[key] = buffer.toString('base64')
	const area = TEXT_AREAS.find((a) => a.match.test(key))
	if (area) textColors[key] = textColor(PNG.sync.read(buffer), area)
}

const lines = [
	'// Generated by scripts/build-preset-icons.mjs - do not edit by hand',
	'',
	'/** 256x256 preset button icons (base64 PNG, as used by png64), from assets/presets */',
	'export const presetImages = {',
	...Object.entries(images).map(([key, data]) => `\t${key}:\n\t\t'${data}',`),
	'} as const',
	'',
	'export type PresetImage = keyof typeof presetImages',
	'',
	'/** Text colour for the icons that leave an empty area for text, picked to contrast with that area */',
	'export const presetTextColors = {',
	...Object.entries(textColors).map(([key, color]) => `\t${key}: ${color},`),
	'} as const',
	'',
]
const target = path.join(root, 'src/images-presets.ts')
const options = await prettier.resolveConfig(target)
fs.writeFileSync(target, await prettier.format(lines.join('\n'), { ...options, filepath: target }))

console.log(
	`Wrote ${Object.keys(images).length} icons (${Object.keys(textColors).length} templates) to src/images-presets.ts`,
)
