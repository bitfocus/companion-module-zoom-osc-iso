/**
 * Splits the mic / camera / hand icons out of the pre-composited participant images in src/images.ts
 * into standalone 72x72 transparent layers for the layered (v2) participant presets.
 *
 * Writes assets/layers/*.png and regenerates src/images-layers.ts.
 * Run with: node scripts/extract-layer-icons.mjs
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { PNG } from 'pngjs'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const imagesSource = fs.readFileSync(path.join(root, 'src/images.ts'), 'utf8')

function loadComposite(key) {
	const match = new RegExp(`\\b${key}:\\s*'([A-Za-z0-9+/=]+)'`).exec(imagesSource)
	if (!match) throw new Error(`Image ${key} not found in src/images.ts`)
	return PNG.sync.read(Buffer.from(match[1], 'base64'))
}

// All icons sit on the same rows at the bottom of the 72x72 composites; the columns are separated by clear gaps
const ICON_ROWS = { from: 53, to: 71 }
const ICON_COLUMNS = { mic: { from: 5, to: 18 }, camera: { from: 24, to: 43 }, hand: { from: 51, to: 65 } }

const allOn = loadComposite('BottomAllAllOn')
const allOff = loadComposite('BottomAllAllOff')

const layers = {
	micOn: [allOn, 'mic'],
	micOff: [allOff, 'mic'],
	cameraOn: [allOn, 'camera'],
	cameraOff: [allOff, 'camera'],
	handRaised: [allOn, 'hand'],
	handLowered: [allOff, 'hand'],
}

fs.mkdirSync(path.join(root, 'assets/layers'), { recursive: true })

const dataUris = {}
for (const [name, [source, icon]] of Object.entries(layers)) {
	const columns = ICON_COLUMNS[icon]
	const layer = new PNG({ width: source.width, height: source.height })
	layer.data.fill(0)
	for (let y = ICON_ROWS.from; y <= ICON_ROWS.to; y++) {
		for (let x = columns.from; x <= columns.to; x++) {
			const offset = (y * source.width + x) * 4
			source.data.copy(layer.data, offset, offset, offset + 4)
		}
	}

	const png = PNG.sync.write(layer)
	fs.writeFileSync(path.join(root, 'assets/layers', `${name}.png`), png)
	dataUris[name] = `data:image/png;base64,${png.toString('base64')}`
}

const lines = [
	'// Generated by scripts/extract-layer-icons.mjs - do not edit by hand',
	'',
	'/** Standalone 72x72 participant status layers (data URIs) used by the layered participant presets */',
	'export const layerImages = {',
	...Object.entries(dataUris).map(([name, uri]) => `\t${name}:\n\t\t'${uri}',`),
	'}',
	'',
]
fs.writeFileSync(path.join(root, 'src/images-layers.ts'), lines.join('\n'))

console.log(`Wrote ${Object.keys(dataUris).length} layers to assets/layers and src/images-layers.ts`)
